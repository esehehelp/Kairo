-- Kairo coordination schema, version 1 (PostgreSQL).
--
-- Conventions, kept from the SQLite schema this replaces so an import is a
-- straight copy of every row:
--  * Times are TEXT: RFC 3339 UTC as the code writes them (time.RFC3339Nano,
--    or the fixed-width sampleStamp of device samples). The code compares
--    them as text in places, so the database must be created with the "C"
--    collation (Open refuses another one); comparisons that must be by time
--    cast to timestamptz.
--  * Flags (0/1 in SQLite) are BOOLEAN.
--  * JSON documents are TEXT holding the exact text the code wrote (digests
--    and comparisons depend on it); queries that look inside cast to jsonb.
--  * Integers are BIGINT; reals are DOUBLE PRECISION.
--
-- Changes are numbered migrations (migrations/NNNN_*.sql), applied in order
-- by Open; schema_version records which ones a database has.

CREATE TABLE schema_version(
 version BIGINT PRIMARY KEY,
 applied_at TEXT NOT NULL
);

