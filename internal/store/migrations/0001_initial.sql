-- Finding the leases of a device (every sample, and every sameDevice check)
-- starts from its resource rows.
CREATE INDEX lease_items_resource_idx ON lease_items(resource_id);
-- A GPU is in at most one live lease. Writers are serialized (Store.write),
-- so the check cannot race another insert.
CREATE FUNCTION exclusive_resource_lease_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.resource_id IS NOT NULL AND NEW.kind='gpu' AND EXISTS(
  SELECT 1 FROM lease_items li JOIN leases l ON l.id=li.lease_id
  WHERE li.resource_id=NEW.resource_id AND li.kind='gpu'
  AND l.state IN('reserved','prepared','active','releasing','stale','revocation_requested')) THEN
  RAISE EXCEPTION 'resource already leased';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER exclusive_resource_lease_guard BEFORE INSERT ON lease_items
 FOR EACH ROW EXECUTE FUNCTION exclusive_resource_lease_guard();
