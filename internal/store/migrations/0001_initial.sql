 last_seen_at TEXT NOT NULL
);

-- Device power and operating point (device_samples.go).
--
-- device_samples: what a provider read of a device at one time. A device is
-- its physical identity (a GPU's UUID; a node's CPU package is that node's
-- cpu resource; a host's CPU package as its controller reads it is
-- "host/<host>/cpu"), so the providers of a shared GPU add to one series;
-- resource_id is the row whose provider reported the sample (NULL for a
-- controller's sample, which has no resource row). Times are fixed-width UTC
-- (sampleStamp), so they order as text. A column is NULL when the device or
-- its driver does not report it.
CREATE TABLE device_samples(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 device TEXT NOT NULL,
 resource_id TEXT REFERENCES resource_instances(id),
 observed_at TEXT NOT NULL,
 valid_until TEXT NOT NULL,
 power_w DOUBLE PRECISION,
 power_limit_w DOUBLE PRECISION,
 sm_clock_mhz BIGINT,
 mem_clock_mhz BIGINT,
 pstate TEXT,
 event_reasons BIGINT,
 mem_util DOUBLE PRECISION,
 fan_pct DOUBLE PRECISION,
 pcie_gen BIGINT,
 pcie_width BIGINT
);
CREATE INDEX device_samples_device_idx ON device_samples(device,observed_at);
-- device_properties: what hardly changes of a device (a GPU's default, least
-- and greatest power limit, its greatest clocks and PCIe link), as last
-- reported.
CREATE TABLE device_properties(
 device TEXT PRIMARY KEY,
 default_power_limit_w DOUBLE PRECISION,
 min_power_limit_w DOUBLE PRECISION,
 max_power_limit_w DOUBLE PRECISION,
 max_sm_clock_mhz BIGINT,
 max_mem_clock_mhz BIGINT,
 pcie_gen_max BIGINT,
 pcie_width_max BIGINT,
 observed_at TEXT NOT NULL
);
-- attempt_energy: the energy the GPUs of an attempt's lease used while it
-- ran, added up as their samples arrive. gpu_seconds_covered is the
-- device-seconds integrated; partial is set once part of the run could not be
-- (a gap between samples, a sample without power, a run Kairo lost track of).
-- policy_*: the device-seconds the operating-point policy's setting was in
-- place on the attempt's GPUs, and the energy its bench profile says that
-- saved for the same work (policy_unestimated_seconds: a setting without a
-- profile to estimate from).
CREATE TABLE attempt_energy(
 attempt_id TEXT PRIMARY KEY REFERENCES attempts(id),
 gpu_joules DOUBLE PRECISION NOT NULL DEFAULT 0,
 gpu_seconds_covered DOUBLE PRECISION NOT NULL DEFAULT 0,
 partial BOOLEAN NOT NULL DEFAULT FALSE,
 policy_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
 policy_saved_joules DOUBLE PRECISION NOT NULL DEFAULT 0,
 policy_unestimated_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
 updated_at TEXT NOT NULL
);

-- Hardware benches and the operating-point policy (hardware_bench.go,
-- device_policy.go). Kept indefinitely: a run is one row and a few hundred
-- points.
--
-- bench_runs: one `kairo hardware bench` of a host's device, run as an
-- ordinary execution (project kairo, queue hardware-bench) whose driver
-- reports through the worker API. state: waiting (not started), running,
-- finished (valid), invalid (finished, but a reference or a kind could not be
-- trusted), failed (the execution ended without results).
CREATE TABLE bench_runs(
 id TEXT PRIMARY KEY,
 host_id TEXT NOT NULL,
 device_id TEXT NOT NULL,
 class TEXT NOT NULL CHECK(class IN('gpu','cpu','storage','network')),
 kinds_json TEXT NOT NULL,
 node_id TEXT NOT NULL,
 peer_node_id TEXT,
 target TEXT NOT NULL DEFAULT '',
 execution_id TEXT NOT NULL REFERENCES execution_requests(id),
 state TEXT NOT NULL CHECK(state IN('waiting','running','finished','invalid','failed')),
 requested_by TEXT NOT NULL,
 created_at TEXT NOT NULL,
 started_at TEXT,
 ended_at TEXT,
 driver_build TEXT,
 versions_json TEXT,
 driver_version TEXT,
 device_json TEXT,
 idle_temperature_c DOUBLE PRECISION,
 references_json TEXT,
 valid BOOLEAN,
 reason TEXT
);
CREATE INDEX bench_runs_device_idx ON bench_runs(host_id,device_id,created_at);
CREATE INDEX bench_runs_state_idx ON bench_runs(state);
-- The executions of a run: the run's own, and the members of a network gang.
CREATE TABLE bench_run_executions(
 execution_id TEXT PRIMARY KEY REFERENCES execution_requests(id),
 run_id TEXT NOT NULL REFERENCES bench_runs(id),
 rank BIGINT NOT NULL
);
-- bench_points: one measurement of a run: a kind (workload) at a setting.
CREATE TABLE bench_points(
 run_id TEXT NOT NULL REFERENCES bench_runs(id),
 seq BIGINT NOT NULL,
 kind TEXT NOT NULL,
 phase TEXT NOT NULL CHECK(phase IN('reference','sweep','measure')),
 settings_json TEXT NOT NULL,
 metrics_json TEXT NOT NULL,
 valid BOOLEAN NOT NULL,
 flags_json TEXT NOT NULL,
 measured_at TEXT NOT NULL,
 PRIMARY KEY(run_id,seq)
);
-- device_policy: the operating point the policy last chose for a device, with
-- its inputs (the history is in the device_policy_decision events).
CREATE TABLE device_policy(
 host_id TEXT NOT NULL,
 device_id TEXT NOT NULL,
 decision_json TEXT NOT NULL,
 decided_at TEXT NOT NULL,
 PRIMARY KEY(host_id,device_id)
);
